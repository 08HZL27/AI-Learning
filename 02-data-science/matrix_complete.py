# ============================================
# 矩阵乘法三步走：从入门到"哦！"
# 规则只有一条：一行 × 一列，对号入座相乘，再全加起来
# ============================================
import numpy as np

# ---------- 第 1 关：成绩加权总分（最生活化） ----------
A = [
    [90, 80, 70],   # 学生1 的三科成绩
    [60, 70, 80],   # 学生2 的三科成绩
]
B = [
    [0.3],          # 平时 占 30%
    [0.2],          # 期中 占 20%
    [0.5],          # 期末 占 50%
]

print("========== 第 1 关：成绩加权 ==========")
print("学生1 总分 = 90×0.3 + 80×0.2 + 70×0.5")
print("           =", 90*0.3, "+", 80*0.2, "+", 70*0.5)
print("           =", 90*0.3 + 80*0.2 + 70*0.5)
print()
print("numpy 验证:", np.array(A) @ np.array(B))

# ---------- 第 2 关：你的小练习（学生3） ----------
print("\n========== 第 2 关：你的练习 ==========")
s3 = 80*0.3 + 90*0.2 + 60*0.5
print("学生3 总分 = 80×0.3 + 90×0.2 + 60×0.5 =", s3)

# ---------- 第 3 关：旋转+缩放（同一规则，换了数字） ----------
R = np.array([[0, -1],
              [1,  0]])     # 旋转 90°
S = np.array([[2, 0],
              [0, 2]])      # 放大 2 倍
p = np.array([1.0, 0.0])    # 测试点 (1, 0)

print("\n========== 第 3 关：旋转+缩放 ==========")
print("点 (1,0) 旋转后:", R @ p)
print("再放大 2 倍  :", S @ (R @ p))
print("合成一步     :", (S @ R) @ p)
print("\n结论：规则从头到尾就一条——一行×一列，相乘再相加")
