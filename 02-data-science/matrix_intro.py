# 矩阵乘法入门：成绩加权总分
# 规则：一行 × 一列，对号入座相乘，再加起来

A = [
    [90, 80, 70],   # 学生1 的三科成绩
    [60, 70, 80],   # 学生2 的三科成绩
]
B = [
    [0.3],          # 平时 占 30%
    [0.2],          # 期中 占 20%
    [0.5],          # 期末 占 50%
]

print("=== 手算：学生1 的总分 ===")
print("90×0.3 =", 90*0.3)
print("80×0.2 =", 80*0.2)
print("70×0.5 =", 70*0.5)
s1 = 90*0.3 + 80*0.2 + 70*0.5
print("加起来 =", s1)

print("\n=== 手算：学生2 的总分 ===")
s2 = 60*0.3 + 70*0.2 + 80*0.5
print("60×0.3 + 70×0.2 + 80×0.5 =", s2)

print("\n=== 用 numpy 的 @ 算（一行搞定）===")
import numpy as np
A_np = np.array(A)
B_np = np.array(B)
result = A_np @ B_np
print("结果表格（每行一个学生的总分）:")
print(result)
print("\n和手算一样吗？", s1 == result[0, 0] and s2 == result[1, 0])
